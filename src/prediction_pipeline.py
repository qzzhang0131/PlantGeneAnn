"""Shared extraction, tokenization, and direct-write prediction pipeline."""

import logging
import os
import shutil
import sys
import time
from dataclasses import replace
from typing import Optional

from datasets import config as datasets_config

from .chromosome_writer import (
    cleanup_temporary_chromosome_h5,
    initialize_chromosome_h5,
    prepare_chromosome_h5_output,
    promote_chromosome_h5,
)
from .configuration import DEFAULT_INFERENCE_MIXED_PRECISION, PipelineConfig
from .runtime import (
    FastaRuntimePolicy,
    cleanup_fasta_runtime_cache,
    cleanup_prediction_work_cache,
    configure_single_threaded_libraries,
    ensure_prediction_disk_space,
    prepare_genome_fasta,
    resolve_dataloader_workers_per_rank,
    resolve_num_processes,
    run_accelerate_subprocess,
)
from .sequence_extractor import SequenceExtractor
from .sequence_tokenizer import SequenceTokenizer

logger = logging.getLogger("PlantGeneAnn")


def _configure_huggingface_cache(cache_path: str) -> str:
    """Route HuggingFace runtime caches into the pipeline cache directory."""

    datasets_dir = os.path.join(cache_path, "datasets")
    datasets_config.HF_DATASETS_CACHE = datasets_dir
    os.environ["HF_HOME"] = os.path.join(cache_path, "huggingface")
    os.environ["HF_DATASETS_CACHE"] = datasets_dir
    return datasets_dir


def _remove_stale_tokenized_chunks(cache_path: str, num_chunks: int) -> None:
    """Remove only the tokenized chunk directories this run will replace."""

    for chunk_number in range(1, num_chunks + 1):
        stale_chunk_dir = os.path.join(cache_path, f"chunk_{chunk_number}")
        if os.path.isdir(stale_chunk_dir):
            shutil.rmtree(stale_chunk_dir)


def _remove_chunk_tsv_files(cache_path: str, num_chunks: int) -> int:
    """Remove only the sequence-window TSV files generated by this run."""

    removed_count = 0
    for chunk_number in range(1, num_chunks + 1):
        chunk_tsv_path = os.path.join(cache_path, f"chunk_{chunk_number}.tsv")
        if os.path.isfile(chunk_tsv_path):
            os.remove(chunk_tsv_path)
            removed_count += 1
    return removed_count


def _run_prediction_stage_impl(
    pipeline_config: PipelineConfig,
    *,
    output_h5_path: str,
    annotator_script: str,
    num_processes: Optional[int] = None,
    compression: str = "none",
    compression_level: int = 4,
    verbose: bool = False,
    total_steps: int = 3,
) -> str:
    """Implement the shared FASTA-to-chromosome-HDF5 prediction stages.

    Stale tokenized directories for the exact chunks produced by this run are
    removed before tokenization so ``save_to_disk`` cannot collide with outputs
    from an earlier run. Prediction runtime datasets are disposable and are
    removed by the owning pipeline after inference.

    ``total_steps`` is retained for compatibility with existing Python callers;
    user-facing logs no longer include numeric step prefixes.
    """

    # Process auto-detection and validation are owned by this shared stage so
    # both entry points follow exactly the same resource path. Resolve before
    # creating cache directories to fail cleanly on invalid CLI values.
    effective_num_processes = resolve_num_processes(num_processes)
    dataloader_workers_per_rank = resolve_dataloader_workers_per_rank(
        pipeline_config.num_cpu_threads,
        effective_num_processes,
    )

    cache_path = os.path.abspath(pipeline_config.cache_path)
    os.makedirs(cache_path, exist_ok=True)
    datasets_dir = _configure_huggingface_cache(cache_path)

    configure_single_threaded_libraries()
    resolved_fasta = prepare_genome_fasta(
        pipeline_config.input_fasta,
        cache_path,
    )
    if resolved_fasta != os.path.abspath(pipeline_config.input_fasta):
        pipeline_config = replace(pipeline_config, input_fasta=resolved_fasta)

    step_start = time.time()
    logger.info("Extracting sequence windows...")
    sequence_extractor = SequenceExtractor(pipeline_config)
    chrom_sequence_info, num_chunks = sequence_extractor.process()
    total_windows = sum(
        num_windows for _, num_windows in chrom_sequence_info.values()
    )
    logger.info(
        "Extraction completed - windows=%d, chunks=%d, elapsed=%.1fs",
        total_windows,
        num_chunks,
        time.time() - step_start,
    )

    step_start = time.time()
    logger.info("Tokenizing sequence windows...")
    if os.path.exists(datasets_dir):
        shutil.rmtree(datasets_dir)
    _remove_stale_tokenized_chunks(cache_path, num_chunks)

    sequence_tokenizer = SequenceTokenizer(pipeline_config)
    sequence_tokenizer.process(num_chunks)

    if os.path.exists(datasets_dir):
        shutil.rmtree(datasets_dir)
    removed_tsv_count = _remove_chunk_tsv_files(cache_path, num_chunks)
    logger.debug(
        "Removed %d chunk TSV file(s) after tokenization",
        removed_tsv_count,
    )
    logger.info(
        "Tokenization completed - elapsed=%.1fs",
        time.time() - step_start,
    )

    step_start = time.time()

    chromosome_h5_path = os.path.abspath(output_h5_path)
    ensure_prediction_disk_space(
        chromosome_h5_path=chromosome_h5_path,
        chrom_sequence_info=chrom_sequence_info,
    )
    chromosome_h5_path, temporary_chromosome_h5_path = (
        prepare_chromosome_h5_output(chromosome_h5_path)
    )

    try:
        initialize_chromosome_h5(
            temporary_chromosome_h5_path,
            chrom_sequence_info,
            compression=compression,
            compression_level=compression_level,
            hdf5_chunk_bp=pipeline_config.center_length,
        )
        logger.info(
            "Running model inference - %d process(es)",
            effective_num_processes,
        )
        accelerate_cmd = [
            sys.executable,
            "-m",
            "accelerate.commands.launch",
            "--num_processes",
            str(effective_num_processes),
            "--num_machines",
            "1",
            "--mixed_precision",
            DEFAULT_INFERENCE_MIXED_PRECISION,
            "--dynamo_backend",
            "no",
        ]
        if effective_num_processes > 1:
            # Accelerate otherwise auto-enables multi-GPU mode and emits a
            # defaults-used warning even when --num_processes is explicit.
            accelerate_cmd.append("--multi_gpu")
        accelerate_cmd.extend(
            [
                os.path.abspath(annotator_script),
                "--model_path",
                pipeline_config.model_path,
                "--cache_path",
                cache_path,
                "--output_h5_path",
                temporary_chromosome_h5_path,
                "--num_chunks",
                str(num_chunks),
                "--batch_size",
                str(pipeline_config.batch_size),
                "--num_workers",
                str(dataloader_workers_per_rank),
            ]
        )
        if verbose:
            accelerate_cmd.append("--verbose")
        run_accelerate_subprocess(accelerate_cmd)
        promote_chromosome_h5(
            temporary_chromosome_h5_path,
            chromosome_h5_path,
            chrom_sequence_info,
            expected_num_chunks=num_chunks,
        )
    finally:
        try:
            cleanup_temporary_chromosome_h5(temporary_chromosome_h5_path)
        except OSError as cleanup_error:
            logger.warning(
                "Could not remove temporary prediction HDF5 %s: %s",
                temporary_chromosome_h5_path,
                cleanup_error,
            )

    logger.info(
        "Model inference completed - elapsed=%.1fs",
        time.time() - step_start,
    )
    return chromosome_h5_path


def run_prediction_stage(
    pipeline_config: PipelineConfig,
    *,
    output_h5_path: str,
    annotator_script: str,
    num_processes: Optional[int] = None,
    compression: str = "none",
    compression_level: int = 4,
    fasta_runtime_policy: FastaRuntimePolicy = (
        FastaRuntimePolicy.CLEAN_AFTER_PREDICTION
    ),
    verbose: bool = False,
    total_steps: int = 3,
) -> str:
    """Run prediction with an explicit, minimal runtime-cache boundary.

    Prediction work cache is always removed before this function returns or
    propagates an exception. FASTA materializations and indexes are retained only
    after successful prediction when ``fasta_runtime_policy`` is
    ``RETAIN_FOR_DECODING``. Temporary HDF5 files remain stage-owned, while the
    completed prediction HDF5 is always returned to and owned by the caller.
    """

    policy = FastaRuntimePolicy(fasta_runtime_policy)
    cache_path = os.path.abspath(pipeline_config.cache_path)
    prediction_succeeded = False
    try:
        chromosome_h5_path = _run_prediction_stage_impl(
            pipeline_config,
            output_h5_path=output_h5_path,
            annotator_script=annotator_script,
            num_processes=num_processes,
            compression=compression,
            compression_level=compression_level,
            verbose=verbose,
            total_steps=total_steps,
        )
        prediction_succeeded = True
        return chromosome_h5_path
    finally:
        cleanup_prediction_work_cache(cache_path)
        retain_fasta_runtime = (
            prediction_succeeded
            and policy is FastaRuntimePolicy.RETAIN_FOR_DECODING
        )
        if not retain_fasta_runtime:
            cleanup_fasta_runtime_cache(cache_path)
